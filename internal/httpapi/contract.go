// The HTTP contract shared with the web app: enum values, response shapes and
// error codes. TypeScriptContract renders it as web/src/lib/api.gen.ts
// (`go run ./cmd/gentypes`); TestContractUpToDate fails when the
// checked-in file is stale, so a change on the Go side cannot drift silently.

// contractEnums: TypeScript union name → allowed values.
var contractEnums = []struct {
	name   string
	values []string
}{
	{"Role", []string{authz.RoleAdmin, authz.RoleMember, authz.RoleViewer}},
	{"ProjectStatus", projectStatuses},
	{"Kind", blockKinds},
	{"CodeLang", codeLangs},
	{"NoteColor", noteColors},
	{"FavoriteKind", favoriteKinds},
	{"TemplateKind", []string{service.KindChecklist, service.KindTable}},
	{"ClientPrefKey", clientPrefKeys},
	{"ActivityKind", []string{
		service.ActProjectCreated, service.ActRenamed, service.ActStatus, service.ActDates, service.ActOwner,
		service.ActTags, service.ActRedmine, service.ActChecklistCreated, service.ActChecklistDone,
		service.ActChecklistDeleted, service.ActItemDone, service.ActFileAdded, service.ActFileDeleted,
		service.ActTableCreated, service.ActTableDeleted,
	}},
}

// contractTypes: TypeScript interface name → Go response type (as encoded by writeJSON).
var contractTypes = []struct {
	name string
	v    any
}{
	{"ApiUser", userDTO{}},
	{"ApiProject", sqlc.Project{}},
	{"ApiCustomer", sqlc.Customer{}},
	{"ApiTag", sqlc.Tag{}},
	{"ApiItem", itemDTO{}},
	{"ApiChecklist", checklistDTO{}},
	{"ApiTable", tableDTO{}},
	{"ApiTemplateItem", sqlc.TemplateItem{}},
	{"ApiActivityEntry", sqlc.ListProjectActivityRow{}},
}

// TypeScriptContract renders the contract. srcDir is the directory of this
// package's sources (scanned for the error codes).
func TypeScriptContract(srcDir string) ([]byte, error) {
	codes, err := errorCodes(srcDir)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by `go run ./cmd/gentypes`. DO NOT EDIT.\n")
	b.WriteString("// Source: internal/httpapi/contract.go\n")
	for _, e := range contractEnums {
		fmt.Fprintf(&b, "\nexport const %s_VALUES = %s as const;\n", constName(e.name), tsList(e.values))
		fmt.Fprintf(&b, "export type %s = (typeof %s_VALUES)[number];\n", e.name, constName(e.name))
	}
	fmt.Fprintf(&b, "\n/** Error codes the API returns in {\"error\": code}; translated as errors.<code>. */\n")
	fmt.Fprintf(&b, "export const ERROR_CODES = %s as const;\n", tsList(codes))
	b.WriteString("export type ErrorCode = (typeof ERROR_CODES)[number];\n")
	for _, t := range contractTypes {
		fmt.Fprintf(&b, "\nexport interface %s {\n", t.name)
		writeFields(&b, reflect.TypeOf(t.v))
		b.WriteString("}\n")
	}
	return b.Bytes(), nil
}

func constName(name string) string {
	var out []rune
	for i, r := range name {
		if i > 0 && r >= 'A' && r <= 'Z' {
			out = append(out, '_')
		}
		out = append(out, r)
	}
	return strings.ToUpper(string(out))
}

func tsList(vals []string) string {
	q := make([]string, len(vals))
	for i, v := range vals {
		q[i] = "'" + strings.ReplaceAll(v, "'", `\'`) + "'"
	}
	return "[" + strings.Join(q, ", ") + "]"
}

var (
	timeType   = reflect.TypeOf(time.Time{})
	rawType    = reflect.TypeOf(json.RawMessage{})
	nullString = reflect.TypeOf(sql.NullString{})
)

func writeFields(b *bytes.Buffer, t reflect.Type) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.Anonymous && f.Type.Kind() == reflect.Struct {
			writeFields(b, f.Type)
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" || !f.IsExported() {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name
		}
		opt := ""
		if strings.Contains(opts, "omitempty") {
			opt = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, opt, tsType(f.Type))
	}
}

var jsonMarshaler = reflect.TypeOf((*json.Marshaler)(nil)).Elem()

func tsType(t reflect.Type) string {
	for _, ct := range contractTypes {
		if reflect.TypeOf(ct.v) == t {
			return ct.name
		}
	}
	switch {
	case t != timeType && t.Implements(jsonMarshaler):
		return "unknown" // custom encoding (e.g. dbtypes.JSONText: embedded JSON)
	case t == timeType:
		return "string"
	case t == rawType:
		return "unknown"
	case t == nullString:
		panic("sql.NullString encodes as an object; use *string in response types")
	}
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem()) + " | null"
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice:
		el := tsType(t.Elem())
		if strings.Contains(el, " ") {
			el = "(" + el + ")"
		}
		return el + "[]"
	case reflect.Map:
		return "Record<string, " + tsType(t.Elem()) + ">"
	case reflect.Struct:
		var b bytes.Buffer
		b.WriteString("{\n")
		writeFields(&b, t)
		b.WriteString("}")
		return b.String()
	case reflect.Interface:
		return "unknown"
	}
	panic("no TypeScript type for " + t.String())
}

// errorCodes collects the codes passed as string literals to errBadRequest,
// errConflict … and in httpError{Msg: …} in the package's sources.
func errorCodes(srcDir string) ([]string, error) {
	files, err := filepath.Glob(filepath.Join(srcDir, "*.go"))
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	seen := map[string]bool{}
	add := func(e ast.Expr) {
		if lit, ok := e.(*ast.BasicLit); ok && lit.Kind == token.STRING {
			if s, err := strconv.Unquote(lit.Value); err == nil && s != "" && s != "validation" {
				seen[s] = true
			}
		}
	}
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return nil, err
		}
		ast.Inspect(f, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.CallExpr:
				if id, ok := n.Fun.(*ast.Ident); ok && strings.HasPrefix(id.Name, "err") && len(n.Args) == 1 {
					add(n.Args[0])
				}
			case *ast.CompositeLit:
				if id, ok := n.Type.(*ast.Ident); ok && id.Name == "httpError" {
					for _, el := range n.Elts {
						if kv, ok := el.(*ast.KeyValueExpr); ok {
							if k, ok := kv.Key.(*ast.Ident); ok && k.Name == "Msg" {
								add(kv.Value)
							}
						}
					}
				}
			}
			return true
		})
	}
	codes := make([]string, 0, len(seen))
	for c := range seen {
		codes = append(codes, c)
	}
	slices.Sort(codes)
	return codes, nil
}
